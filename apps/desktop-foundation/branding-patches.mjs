// local directory discovery and internal storage keys/package formats.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const AIKING_DOCS = "https://github.com/aikingcorp-spec/AIKINGX_Bot/blob/AIKINGBOT/docs/aikingbot";

const DOC_LINKS = [
  ["https://github.com/milind-soni/OpenMausBot/blob/main/docs/self-hosting.md#connect-a-", `${AIKING_DOCS}/server-deployment.md#custom-domain-`],
  ["https://github.com/milind-soni/OpenMausBot/blob/main/docs/self-hosting.md", `${AIKING_DOCS}/server-deployment.md`],
  ["https://github.com/milind-soni/OpenMausBot/blob/main/docs/byo-vps.md", `${AIKING_DOCS}/server-deployment.md#agent-computer-on-a-vps`],
  ["https://github.com/milind-soni/OpenMausBot/blob/main/docs/linux-desktop.md", `${AIKING_DOCS}/linux-desktop.md`],
  ["https://github.com/milind-soni/OpenMausBot/blob/main/docs/tool-selection.md", `${AIKING_DOCS}/tool-selection.md`],
];
const NAMES = [
  [/\\nOpenMausBot/g, "\\nAIKINGBOT"],
  [/\bOpenMaus Bot\b/g, "AIKINGBOT"],
  [/\bOpenMausBot(?! Speech\.app)\b/g, "AIKINGBOT"],
  [/\bMausBot Cloud\b/g, "AIKINGBOT Cloud"],
  [/\bOpenMausMobile\b/g, "AIKINGBOT Mobile"],
  [/\bOpenMaus-managed\b/g, "AIKINGBOT-managed"],
  [/\bOpenMaus (Admin|team|package|backup|keeps|Team|bot)\b/g, "AIKINGBOT $1"],
  [/The MausBot look\./g, "The classic look."],
];
// Files whose remaining upstream names are attribution, pinned downloads or legacy discovery.
const KEEP = new Set([
  "src/lib/app-links.ts", "src/components/AboutDialog.tsx", "server/browser-engine-release.ts", "server/local-computer.ts",
  "electron/build-speech-helper.mjs", "electron/speech.mjs",
]);
const TEST = /(?:\.test\.|\.spec\.|node-test|\/test\/|__tests__|\/fixtures?\/|\/testing\/)/;

function rebrand(text) {
  let next = text;
  for (const [from, to] of DOC_LINKS) next = next.replaceAll(from, to);
  // A URL path segment keeps the upstream spelling; only prose and identities change.
  return NAMES.reduce((value, [pattern, replacement]) => value.replace(pattern, (match, ...rest) => {
    const offset = rest.at(-2); const before = value.slice(Math.max(0, offset - 1), offset);
    return before === "/" ? match : match.replace(pattern, replacement);
  }), next);
}

export function patchBranding(source) {
  const changes = [];
  const edit = (path, change) => {
    const file = join(source, path); const before = readFileSync(file, "utf8").replaceAll("\r\n", "\n"); const after = change(before);
    if (after === before) throw new Error(`Branding patch anchor changed: ${path}`);
    writeFileSync(file, after); changes.push(path);
  };
  const visit = (directory) => {
    for (const entry of readdirSync(join(source, directory), { withFileTypes: true })) {
      const path = `${directory}/${entry.name}`;
      if (entry.isDirectory()) { if (entry.name !== "vendor" && entry.name !== "node_modules") visit(path); continue; }
      if (!/\.(?:ts|tsx|mjs|cjs)$/.test(entry.name) || TEST.test(path) || KEEP.has(path)) continue;
      const file = join(source, path); const before = readFileSync(file, "utf8"); const after = rebrand(before);
      if (after !== before) { writeFileSync(file, after); changes.push(path); }
    }
  };
  for (const directory of ["src", "server", "electron", "shared"]) visit(directory);

  // Translations: product names only; English is generated by terminology.mjs.
  const locales = join(source, "src/locales");
  for (const name of readdirSync(locales)) {
    if (!name.endsWith(".json") || name === "en.json" || name === "source-hashes.json") continue;
    const file = join(locales, name); const before = readFileSync(file, "utf8");
    const after = NAMES.reduce((value, [pattern, replacement]) => value.replace(pattern, replacement), before).replace(/\bMausBot\b/g, "AIKINGBOT");
    if (after !== before) { writeFileSync(file, after); changes.push(`src/locales/${name}`); }
  }

  // Electron node tests run against the source directly (security-checks.mjs), not through compatibility.mjs:
  // they get the same product names, and the Cloud bridge tests run with a configured AIKING Cloud.
  for (const name of readdirSync(join(source, "electron"))) {
    if (!name.endsWith(".node-test.mjs")) continue;
    const file = join(source, "electron", name); const before = readFileSync(file, "utf8");
    let after = rebrand(before);
    if (name === "cloud-account-ipc.node-test.mjs" || name === "cloud-move.node-test.mjs") after = after.replaceAll('"--omb-company-desktop=1"', '"--omb-company-desktop=1", "--aiking-cloud=1"');
    // Main's Cloud handlers and offers are additionally gated on AIKING_CLOUD_ORIGIN (shipping patches).
    if (name === "cloud-account-ipc.node-test.mjs") after = after.replace("rendererOrigin: () => origin, environmentsState:", 'process: { env: { AIKING_CLOUD_ORIGIN: "https://cloud.example.test" } }, rendererOrigin: () => origin, environmentsState:');
    if (name === "cloud-entry.node-test.mjs") after = after.replace("/return app\\.isPackaged && !desktopRemoteAccess && brandedBuild === false;/", "/return Boolean\\(process\\.env\\.AIKING_CLOUD_ORIGIN\\) && app\\.isPackaged && !desktopRemoteAccess && brandedBuild === false;/");
    if (after !== before) { writeFileSync(file, after); changes.push(`electron/${name}`); }
  }

  // Upstream Cloud account/plan/move/lending surfaces exist only when an AIKING Cloud origin is configured;
  // organization sign-in and company backups keep the packaged-desktop flag.
  edit("electron/main.mjs", text => text.replace('...(app.isPackaged && !desktopRemoteAccess ? ["--omb-company-desktop=1"] : [])',
    '...(app.isPackaged && !desktopRemoteAccess ? ["--omb-company-desktop=1", ...(process.env.AIKING_CLOUD_ORIGIN ? ["--aiking-cloud=1"] : [])] : [])'));
  edit("electron/preload.cjs", text => {
    const next = ["cloudAccount", "cloudMove", "cloudLending", "cloudPlan"].reduce((value, name) => value.replace(
      `  ${name}: process.argv.includes("--omb-company-desktop=1") ? {`, `  ${name}: process.argv.includes("--omb-company-desktop=1") && process.argv.includes("--aiking-cloud=1") ? {`), text);
    if (next.split("--aiking-cloud=1").length !== 5) throw new Error("Branding patch anchor changed: electron/preload.cjs cloud bridges");
    return next;
  });

  // The aikingbot:// protocol (shipping patches) must also be recognized where upstream compares or matches it
  // without the literal "openmausbot://" text: package install links and wrapped chat thread links.
  edit("electron/package-link.mjs", text => text.replace('link.protocol !== "openmausbot:"', 'link.protocol !== "aikingbot:"'));
  // The updater's relaunch must drop the organization deep link under its AIKINGBOT spelling too.
  for (const path of ["scripts/patch-organization-updater.mjs", "electron/vendor/electron-updater.cjs"]) {
    edit(path, text => text.replaceAll('arg !== "openmausbot://organization"', 'arg !== "aikingbot://organization"'));
  }
  edit("src/lib/thread-refs.ts", text => text.replace("(openmausbot:\\/\\/thread\\/", "(aikingbot:\\/\\/thread\\/"));

  // Upstream hosted admin portal: no default. Sign-in uses an operator-provided address.
  edit("src/components/OrganizationSettings.tsx", text => text
    .replace('const DEFAULT_PORTAL_ORIGIN = "https://admin.openmausbot.com";', 'const DEFAULT_PORTAL_ORIGIN = "";')
    .replace('        <button type="button" disabled={busy} onClick={() => void perform(() => bridge.begin({ portalOrigin: DEFAULT_PORTAL_ORIGIN }))}',
      '        {DEFAULT_PORTAL_ORIGIN && <button type="button" disabled={busy} onClick={() => void perform(() => bridge.begin({ portalOrigin: DEFAULT_PORTAL_ORIGIN }))}')
    .replace('{busy ? t("organization.working") : t("organization.signIn")}</button>\n        <details className="text-[12px] text-ink-secondary">',
      '{busy ? t("organization.working") : t("organization.signIn")}</button>}\n        <details open={!DEFAULT_PORTAL_ORIGIN} className="text-[12px] text-ink-secondary">')
    .replace("placeholder={DEFAULT_PORTAL_ORIGIN}", 'placeholder={DEFAULT_PORTAL_ORIGIN || "https://admin.example.com"}'));
  edit("src/lib/onboarding.ts", text => text.replace('export const DEFAULT_ADMIN_ORIGIN = "https://admin.openmausbot.com";', 'export const DEFAULT_ADMIN_ORIGIN = "";'));
  edit("src/components/onboarding/beats/OrganisationRow.tsx", text => text.replace(
    "onClick={() => void perform(() => bridge.begin({ portalOrigin: DEFAULT_ADMIN_ORIGIN }))}",
    "onClick={() => DEFAULT_ADMIN_ORIGIN ? void perform(() => bridge.begin({ portalOrigin: DEFAULT_ADMIN_ORIGIN })) : onOpenSettings()}"));
  edit("src/components/RemoteComputerSection.tsx", text => text.replace('placeholder="https://…openmausbot.com or computer.tailnet.ts.net"', 'placeholder="https://computer.example.com or computer.tailnet.ts.net"'));
  // The widget gallery must not fetch upstream marketing images.
  edit("shared/widget-samples.ts", text => text.replace('src: "https://mausbot.com/og.png", alt: "MausBot"', 'src: "/app-icon.svg", alt: "AIKINGBOT"'));
  return changes;
}
